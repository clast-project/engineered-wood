using Apache.Arrow;
using Apache.Arrow.Types;
using EngineeredWood.DeltaLake.Actions;
using EngineeredWood.DeltaLake.Log;
using EngineeredWood.DeltaLake.Schema;
using EngineeredWood.IO.Local;
using System.Text.Json;
using Ex = EngineeredWood.Expressions.Expressions;

namespace EngineeredWood.DeltaLake.Table.Tests;

/// <summary>
/// An UPDATE or MERGE that changes an identity column's value is refused, as Spark refuses it (#654):
/// <c>DELTA_IDENTITY_COLUMNS_UPDATE_NOT_SUPPORTED</c>, for GENERATED ALWAYS and GENERATED BY DEFAULT alike. The
/// high-water mark does not follow the new value, so <c>UpdateAsync</c> used to commit it and the next insert issued
/// it again: two rows with one id.
/// </summary>
public class IdentityUpdateTests : IDisposable
{
    private readonly string _tempDir;

    public IdentityUpdateTests()
    {
        _tempDir = Path.Combine(Path.GetTempPath(), $"delta_identity_update_{Guid.NewGuid():N}");
        Directory.CreateDirectory(_tempDir);
    }

    public void Dispose()
    {
        if (Directory.Exists(_tempDir))
        {
            try { Directory.Delete(_tempDir, recursive: true); } catch { }
        }
    }

    private LocalTableFileSystem Fs => new(_tempDir);

    /// <summary>A table whose <c>id</c> is an identity column (start 1, step 1), holding the row (1, "a").</summary>
    private async Task<DeltaTable> CreateAsync(bool allowExplicitInsert)
    {
        string idMeta = JsonSerializer.Serialize(IdentityColumn.CreateMetadata(1, 1, allowExplicitInsert));
        string schema = $@"{{""type"":""struct"",""fields"":[{{""name"":""id"",""type"":""long"",""nullable"":true,""metadata"":{idMeta}}},{{""name"":""value"",""type"":""string"",""nullable"":true,""metadata"":{{}}}}]}}";
        await new TransactionLog(Fs).WriteCommitAsync(0, new List<DeltaAction>
        {
            new ProtocolAction { MinReaderVersion = 1, MinWriterVersion = 7, WriterFeatures = ["identityColumns"] },
            new MetadataAction { Id = "identity-update", Format = Format.Parquet, SchemaString = schema, PartitionColumns = [] },
        });
        var table = await DeltaTable.OpenAsync(Fs);
        await table.WriteAsync([Values("a")]);
        return table;
    }

    private static RecordBatch Values(params string[] values)
    {
        var builder = new StringArray.Builder();
        foreach (string v in values)
            builder.Append(v);
        return new RecordBatch(
            new Apache.Arrow.Schema.Builder().Field(new Field("value", StringType.Default, true)).Build(),
            [builder.Build()], values.Length);
    }

    private static RecordBatch Row(long id, string value) => new(
        new Apache.Arrow.Schema.Builder()
            .Field(new Field("id", Int64Type.Default, true))
            .Field(new Field("value", StringType.Default, true))
            .Build(),
        [new Int64Array.Builder().Append(id).Build(), new StringArray.Builder().Append(value).Build()], 1);

    /// <summary>The updater: the rows handed to it with <paramref name="column"/> set to <paramref name="value"/>.</summary>
    private static Func<RecordBatch, RecordBatch> Set(string column, IArrowArray value) => batch =>
    {
        int index = batch.Schema.GetFieldIndex(column);
        var columns = Enumerable.Range(0, batch.ColumnCount).Select(batch.Column).ToArray();
        columns[index] = value;
        return new RecordBatch(batch.Schema, columns, batch.Length);
    };

    private async Task<List<(long? Id, string? Value)>> ReadAsync(DeltaTable table)
    {
        var rows = new List<(long?, string?)>();
        await foreach (var batch in table.ReadAllAsync())
        {
            var ids = (Int64Array)batch.Column("id");
            var values = (StringArray)batch.Column("value");
            for (int i = 0; i < batch.Length; i++)
                rows.Add((ids.GetValue(i), values.GetString(i)));
        }
        return rows.OrderBy(r => r.Item1).ThenBy(r => r.Item2).ToList();
    }

    private static async Task AssertRefusedAsync(Func<Task> operation)
    {
        var ex = await Assert.ThrowsAsync<DeltaFormatException>(operation);
        Assert.Equal(DeltaTableErrorCodes.IdentityColumnUpdateNotSupported, ex.ErrorCode);
        Assert.Contains("id", ex.Message);
    }

    /// <summary>The issue's repro: <c>SET id = 5</c>, then four appends that would have generated a second 5.</summary>
    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task Update_ChangingTheIdentityValue_IsRefused_AndLaterInsertsStayUnique(bool byDefault)
    {
        await using var table = await CreateAsync(byDefault);
        long version = table.CurrentSnapshot.Version;

        await AssertRefusedAsync(() => table.UpdateAsync(
            Ex.Equal("value", "a"), Set("id", new Int64Array.Builder().Append(5).Build())).AsTask());

        Assert.Equal(version, (await DeltaTable.OpenAsync(Fs)).CurrentSnapshot.Version);
        await table.WriteAsync([Values("b", "c", "d", "e")]);
        Assert.Equal([(1L, "a"), (2L, "b"), (3L, "c"), (4L, "d"), (5L, "e")], await ReadAsync(table));
    }

    [Fact]
    public async Task Update_ThroughTheDelegatePredicate_IsRefusedToo()
    {
        await using var table = await CreateAsync(allowExplicitInsert: false);

        await AssertRefusedAsync(() => table.UpdateAsync(
            batch => new BooleanArray.Builder().AppendRange(Enumerable.Repeat(true, batch.Length)).Build(),
            Set("id", new Int64Array.Builder().Append(5).Build())).AsTask());
    }

    [Fact]
    public async Task Update_SettingTheIdentityToNull_IsRefused()
    {
        await using var table = await CreateAsync(allowExplicitInsert: true);

        await AssertRefusedAsync(() => table.UpdateAsync(
            Ex.Equal("value", "a"), Set("id", new Int64Array.Builder().AppendNull().Build())).AsTask());
    }

    [Fact]
    public async Task Update_ReturningTheIdentityUnchanged_Writes()
    {
        await using var table = await CreateAsync(allowExplicitInsert: false);

        var (updated, _) = await table.UpdateAsync(
            Ex.Equal("value", "a"), Set("value", new StringArray.Builder().Append("z").Build()));

        Assert.Equal(1, updated);
        Assert.Equal([(1L, "z")], await ReadAsync(table));
    }

    /// <summary>
    /// A GENERATED BY DEFAULT column can hold an explicit NULL. An updater that leaves the column out makes it NULL,
    /// which for that row changes nothing, so the update writes; for a row holding a value it is a change.
    /// </summary>
    [Fact]
    public async Task Update_LeavingOutAnIdentityThatIsAlreadyNull_Writes()
    {
        await using var table = await CreateAsync(allowExplicitInsert: true);
        var nullId = new RecordBatch(Row(0, "n").Schema,
            [new Int64Array.Builder().AppendNull().Build(), new StringArray.Builder().Append("n").Build()], 1);
        await table.WriteAsync([nullId]);
        static RecordBatch DropId(RecordBatch batch) => new(
            new Apache.Arrow.Schema.Builder().Field(batch.Schema.GetFieldByName("value")).Build(),
            [batch.Column("value")], batch.Length);

        var (updated, _) = await table.UpdateAsync(Ex.Equal("value", "n"), DropId);

        Assert.Equal(1, updated);
        Assert.Contains((null, "n"), await ReadAsync(table));
        await AssertRefusedAsync(() => table.UpdateAsync(Ex.Equal("value", "a"), DropId).AsTask());
    }

    /// <summary>
    /// The identity values are read through run-end encoding, which a host reader may hand back: re-encoded with the
    /// same values the column is unchanged, and with another value it is a change.
    /// </summary>
    [Theory]
    [InlineData("unchanged", false)]
    [InlineData("rebuiltSame", false)]
    [InlineData("rebuiltOther", true)]
    public async Task Update_ARunEndEncodedIdentityFromAHostReader_IsComparedByValue(string updater, bool refused)
    {
        await (await CreateAsync(allowExplicitInsert: true)).DisposeAsync();
        var options = DeltaTableOptions.Default with
        {
            DataFileReader = new RunEndEncodedIdReader(),
            DataFileWriter = new DrainingWriter(),
            CollectStats = false,
        };
        await using var table = await DeltaTable.OpenAsync(Fs, options);

        // The input's own REE type instance, so only the values differ from what the reader produced.
        Func<RecordBatch, RecordBatch> update = updater == "unchanged"
            ? batch => batch
            : batch =>
            {
                int index = batch.Schema.GetFieldIndex("id");
                var type = batch.Column(index).Data.DataType;
                var ree = RunEndEncoded(type, updater == "rebuiltSame" ? 1 : 7, batch.Length);
                var columns = Enumerable.Range(0, batch.ColumnCount).Select(batch.Column).ToArray();
                columns[index] = ree;
                return new RecordBatch(batch.Schema, columns, batch.Length);
            };

        if (refused)
        {
            await AssertRefusedAsync(() => table.UpdateAsync(Ex.Equal("value", "a"), update).AsTask());
        }
        else
        {
            var (updated, _) = await table.UpdateAsync(Ex.Equal("value", "a"), update);
            Assert.Equal(1, updated);
        }
    }

    private static RunEndEncodedArray RunEndEncoded(IArrowType? type, long value, int length)
    {
        var runEnds = new Int32Array.Builder().Append(length).Build();
        var values = new Int64Array.Builder().Append(value).Build();
        return type is null
            ? new RunEndEncodedArray(runEnds, values)
            : new RunEndEncodedArray(new ArrayData(type, length, 0, 0, [], [runEnds.Data, values.Data]));
    }

    /// <summary>A host reader that hands the seed row (1, "a") back with <c>id</c> run-end encoded.</summary>
    private sealed class RunEndEncodedIdReader : IDataFileReader
    {
        public async IAsyncEnumerable<RecordBatch> ReadAsync(
            string relativePath, IReadOnlyList<string>? physicalColumns,
            [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken)
        {
            var id = RunEndEncoded(null, 1, 1);
            yield return new RecordBatch(
                new Apache.Arrow.Schema.Builder()
                    .Field(new Field("id", id.Data.DataType, true))
                    .Field(new Field("value", StringType.Default, true))
                    .Build(),
                [id, new StringArray.Builder().Append("a").Build()], 1);
            await Task.CompletedTask;
        }
    }

    /// <summary>A host writer that consumes the batches and stores nothing.</summary>
    private sealed class DrainingWriter : IDataFileWriter
    {
        public async ValueTask<long> WriteAsync(
            IAsyncEnumerable<RecordBatch> batches, string relativePath, CancellationToken cancellationToken)
        {
            await foreach (var _ in batches.WithCancellation(cancellationToken))
            {
            }
            return 1;
        }
    }

    /// <summary>A transaction's UPDATE goes through the same rewrite, so it refuses too.</summary>
    [Fact]
    public async Task Update_InATransaction_IsRefused()
    {
        await using var table = await CreateAsync(allowExplicitInsert: true);
        await using var txn = table.StartTransaction();

        await AssertRefusedAsync(() => txn.UpdateAsync(
            Ex.Equal("value", "a"), Set("id", new Int64Array.Builder().Append(5).Build())).AsTask());
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task Merge_UpdateStar_IsRefusedWithTheCode(bool byDefault)
    {
        await using var table = await CreateAsync(byDefault);

        await AssertRefusedAsync(() => table.MergeAsync(
            [Row(5, "a")], new MergeOptions { Keys = ["value"], WhenMatched = MergeAction.Update }).AsTask());
        await AssertRefusedAsync(() => table.MergeAsync(
            [Row(5, "a")],
            new MergeOptions { Keys = ["value"], WhenMatched = MergeAction.UpdateColumns("id") }).AsTask());

        Assert.Equal([(1L, "a")], await ReadAsync(table));
    }

    [Fact]
    public async Task Merge_UpdateOfOtherColumns_Writes()
    {
        await using var table = await CreateAsync(allowExplicitInsert: true);

        await table.MergeAsync(
            [Row(5, "a")], new MergeOptions { Keys = ["value"], WhenMatched = MergeAction.UpdateColumns("value") });

        Assert.Equal([(1L, "a")], await ReadAsync(table));
    }
}
