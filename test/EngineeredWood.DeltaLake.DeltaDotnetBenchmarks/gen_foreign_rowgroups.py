"""#878: Delta tables whose single data file is one row group of about 1 GB on disk, written by pyarrow.

EW cannot write these itself (a decoded chunk passes Arrow's 2 GB per-array limit), so a foreign writer does.
The Arrow schema is NOT stored in the file (store_schema=False), as Spark or parquet-mr would write it: a reader
sees plain BYTE_ARRAY/UTF8 and must choose a string type itself.

    python gen_foreign_rowgroups.py <root>

Tables (each one file, one row group, ZSTD, page index on):
  fat_str   2.2M rows: id, payload = 1,000 hex chars.  ~2.2 GB of string data in one chunk.
  skew_str  2.4M rows: id, payload = 8,000 hex chars for the first 300K rows, 16 after.  A 262,144-row batch of
            the first rows holds ~2.1 GB, past the 2 GB limit, so a proportional batch share would fail.
  huge_str  2.7M rows: id, payload = 2,000 hex chars.  Not generated by default: the payload chunk is ~2.6 GB
            ON DISK, past what one int-sized buffer can hold (python gen_foreign_rowgroups.py <root> huge_str).
  wide_num  6M rows: id + 20 random doubles.  ~1 GB of fixed-width data in 21 chunks.
"""
import json
import os
import shutil
import sys
import time
import uuid

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq


def hex_strings(rng, lengths):
    """A string array of random hex text, lengths[i] characters each (each length even)."""
    lengths = np.asarray(lengths, dtype=np.int64)
    offsets = np.zeros(len(lengths) + 1, dtype=np.int64)
    np.cumsum(lengths, out=offsets[1:])
    data = rng.bytes(int(offsets[-1]) // 2).hex().encode("ascii")
    return pa.LargeStringArray.from_buffers(len(lengths), pa.py_buffer(offsets), pa.py_buffer(data))


def build(name, rng):
    if name == "fat_str":
        n = 2_200_000
        payload = hex_strings(rng, np.full(n, 1000))
        return pa.table({"id": pa.array(np.arange(n, dtype=np.int64)), "payload": payload})
    if name == "skew_str":
        n, big = 2_400_000, 300_000
        lengths = np.where(np.arange(n) < big, 8000, 16)
        payload = hex_strings(rng, lengths)
        return pa.table({"id": pa.array(np.arange(n, dtype=np.int64)), "payload": payload})
    if name == "huge_str":
        n = 2_700_000
        payload = hex_strings(rng, np.full(n, 2000))
        return pa.table({"id": pa.array(np.arange(n, dtype=np.int64)), "payload": payload})
    if name == "wide_num":
        n = 6_000_000
        cols = {"id": pa.array(np.arange(n, dtype=np.int64))}
        for c in range(20):
            cols[f"d{c:02}"] = pa.array(rng.random(n))
        return pa.table(cols)
    raise ValueError(name)


def delta_type(t):
    if pa.types.is_int64(t):
        return "long"
    if pa.types.is_float64(t):
        return "double"
    if pa.types.is_large_string(t) or pa.types.is_string(t):
        return "string"
    raise ValueError(t)


def write_table(root, name, rng):
    path = os.path.join(root, name)
    shutil.rmtree(path, ignore_errors=True)
    os.makedirs(os.path.join(path, "_delta_log"))
    t0 = time.time()
    table = build(name, rng)
    file_name = f"part-00000-{uuid.uuid4()}.parquet"
    pq.write_table(
        table, os.path.join(path, file_name),
        row_group_size=table.num_rows, compression="zstd", store_schema=False,
        write_page_index=True, use_dictionary=False)
    size = os.path.getsize(os.path.join(path, file_name))
    md = pq.ParquetFile(os.path.join(path, file_name)).metadata
    assert md.num_row_groups == 1, md.num_row_groups

    schema = {"type": "struct", "fields": [
        {"name": f.name, "type": delta_type(f.type), "nullable": True, "metadata": {}} for f in table.schema]}
    now = int(time.time() * 1000)
    actions = [
        {"commitInfo": {"timestamp": now, "operation": "WRITE", "engineInfo": "gen_foreign_rowgroups.py (#878)"}},
        {"protocol": {"minReaderVersion": 1, "minWriterVersion": 2}},
        {"metaData": {"id": str(uuid.uuid4()), "format": {"provider": "parquet", "options": {}},
                      "schemaString": json.dumps(schema), "partitionColumns": [], "configuration": {},
                      "createdTime": now}},
        {"add": {"path": file_name, "partitionValues": {}, "size": size, "modificationTime": now,
                 "dataChange": True,
                 "stats": json.dumps({"numRecords": table.num_rows})}},
    ]
    with open(os.path.join(path, "_delta_log", "00000000000000000000.json"), "w", newline="\n") as f:
        for a in actions:
            f.write(json.dumps(a) + "\n")
    rg = md.row_group(0)
    uncompressed = sum(rg.column(c).total_uncompressed_size for c in range(rg.num_columns))
    print(f"{name}: rows={table.num_rows} file={size / 2**20:.0f} MiB "
          f"uncompressed={uncompressed / 2**20:.0f} MiB ({time.time() - t0:.0f} s)", flush=True)


def main():
    root = sys.argv[1]
    names = sys.argv[2:] or ["fat_str", "skew_str", "wide_num"]
    rng = np.random.default_rng(878)
    for name in names:
        write_table(root, name, rng)


if __name__ == "__main__":
    main()
